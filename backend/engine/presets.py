CUSTOM_PRESETS_STORE: Dict[str, Dict[str, Any]] = {}


def get_all_presets() -> List[Dict[str, Any]]:
    merged = copy.deepcopy(DEFAULT_PRESETS)
    merged.update(copy.deepcopy(CUSTOM_PRESETS_STORE))
    return list(merged.values())


def get_preset(preset_id: str, custom_overrides: Dict[str, Any] | None = None) -> Dict[str, Any]:
    base = DEFAULT_PRESETS.get(preset_id) or CUSTOM_PRESETS_STORE.get(preset_id) or DEFAULT_PRESETS["makalah"]
    preset = copy.deepcopy(base)
    if custom_overrides:
        for k, v in custom_overrides.items():
            if v is not None:
                preset[k] = v
    return preset


def save_custom_preset(preset_data: Dict[str, Any]) -> Dict[str, Any]:
    preset_id = preset_data.get("id") or f"custom_{len(CUSTOM_PRESETS_STORE) + 1}"
    base = copy.deepcopy(DEFAULT_PRESETS["makalah"])
    base.update(preset_data)
    base["id"] = preset_id
    base["is_custom"] = True
    base["margin_label"] = (
        f"{base['margin_top_cm']:g}-{base['margin_left_cm']:g}-"
        f"{base['margin_bottom_cm']:g}-{base['margin_right_cm']:g} cm"
    )
    CUSTOM_PRESETS_STORE[preset_id] = base
    return base
